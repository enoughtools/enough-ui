import { readFile, writeFile } from 'node:fs/promises';

// The web theme remains the authority for Enough's shared palette.
const root = new URL('../', import.meta.url);
const css = await readFile(new URL('src/styles/styles.css', root), 'utf8');
const names = {
  ink: 'ink', inkSecondary: 'ink-2', paper: 'paper', card: 'card', surface: 'surface',
  hairline: 'hairline', hairlineSoft: 'hairline-soft', border: 'border-mid',
  text: 'text-main', secondaryText: 'text-2', muted: 'text-3', hint: 'text-4',
  darkText: 'dark-text', darkSecondaryText: 'dark-text-2', darkMuted: 'dark-text-3',
  accent: 'accent', accentSoft: 'accent-soft', darkAccent: 'accent-on-ink',
  success: 'ok', darkSuccess: 'ok-on-ink', warning: 'warn',
};
const fields = Object.entries(names).map(([name, token]) => {
  const match = css.match(new RegExp(`--color-${token}:\\s*#([a-fA-F0-9]{6})\\s*;`));
  if (!match) throw new Error(`Missing shared color token: ${token}`);
  return `    public static let ${name}: UInt32 = 0x${match[1].toUpperCase()}`;
}).join('\n');
const output = `// Generated by scripts/build-swift-tokens.mjs from src/styles/styles.css.\n// Edit the shared theme, then regenerate.\n\n/// Shared EnoughUI RGB values, available without a view or an appearance.\npublic enum EnoughPalette {\n${fields}\n}\n`;
const destination = new URL('packages/swift/Sources/EnoughUI/Palette.swift', root);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('Swift palette is stale. Run node scripts/build-swift-tokens.mjs.');
} else {
  await writeFile(destination, output);
}
